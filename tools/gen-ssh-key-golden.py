#!/usr/bin/env python3
# SSH のホスト鍵の署名 (RFC 8709 の ssh-ed25519、RFC 8332 の rsa-sha2-256/512) と known_hosts のハッシュされた名前の golden を作り、
# test/ssh/key_test.clay に書く。期待値は別の実装:
#   鍵と署名の blob: paramiko の Ed25519Key / RSAKey が作ったもの (鍵は cryptography で決まった値から作る)
#   ハッシュされた名前: paramiko の HostKeys.hash_host (|1|salt|HMAC-SHA1(salt, 名前))
# 使い方: python3 -I tools/gen-ssh-key-golden.py > test/ssh/key_test.clay  (paramiko 5.0.0、cryptography 49.0.0 で作った)
import base64
import nacl.signing
import paramiko
from paramiko.message import Message
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec, padding, rsa

def pat(n, m, a):
    return bytes((i * m + a) % 256 for i in range(n))

H = pat(32, 7, 3)   # 署名する交換ハッシュ

ed_key = paramiko.Ed25519Key.__new__(paramiko.Ed25519Key)   # paramiko の Ed25519 は pynacl。種 (seed) を決めて作る
ed_key._signing_key = nacl.signing.SigningKey(pat(32, 5, 1))
ed_key._verifying_key = ed_key._signing_key.verify_key
ed_key.public_blob = None
ED_BLOB = ed_key.asbytes()
ED_SIG = ed_key.sign_ssh_data(H).asbytes()
assert ed_key.verify_ssh_sig(H, Message(ED_SIG))

# RSA は鍵の生成が乱数なので、作った鍵の値 (n e d p q) をそのまま使う。golden は鍵ごと書き出すので再現できる
rsa_priv = rsa.generate_private_key(public_exponent=65537, key_size=2048)
rk = paramiko.RSAKey(key=rsa_priv)
RSA_BLOB = rk.asbytes()
RSA_SIG256 = rk.sign_ssh_data(H, "rsa-sha2-256").asbytes()
RSA_SIG512 = rk.sign_ssh_data(H, "rsa-sha2-512").asbytes()
# paramiko 5 は SHA-1 の ssh-rsa を署名しないので、cryptography で署名して blob を組む
m1 = Message(); m1.add_string("ssh-rsa"); m1.add_string(rsa_priv.sign(H, padding.PKCS1v15(), hashes.SHA1()))
RSA_SIG1 = m1.asbytes()
small = paramiko.RSAKey(key=rsa.generate_private_key(public_exponent=65537, key_size=1024))
SMALL_BLOB = small.asbytes()
SMALL_SIG = small.sign_ssh_data(H, "rsa-sha2-256").asbytes()

# ECDSA (RFC 5656): 秘密の値を決めて作る。署名は乱数を使うので毎回違うが、確かめるのは検証だけ
ec_priv = ec.derive_private_key(int.from_bytes(pat(32, 3, 7), "big"), ec.SECP256R1())
ec_key = paramiko.ECDSAKey(vals=(ec_priv, ec_priv.public_key()))
EC_BLOB = ec_key.asbytes()
EC_SIG = ec_key.sign_ssh_data(H).asbytes()
assert ec_key.verify_ssh_sig(H, Message(EC_SIG))

def kh_hash(name, salt):
    return paramiko.HostKeys.hash_host(name, base64.b64encode(salt).decode())

HASH_PLAIN = kh_hash("example.org", pat(20, 3, 1))
HASH_PORT = kh_hash("[127.0.0.1]:2222", pat(20, 9, 4))

def h(x): return x.hex()
def b64(x): return base64.b64encode(x).decode()

print(";; tools/gen-ssh-key-golden.py で作った (手で直さない)。鍵と署名は paramiko 5.0.0、ハッシュされた名前は HostKeys.hash_host")
print("(ns key-test (:require [mulay.lib.sshkey :as k]))")
print()
print("(defn- hexd Int [c: Int] (if (<= c 57) (- c 48) (- c 87)))")
print("(defn- unhex Str [h: &Str]")
print("  (loop [i 0 out \"\"] (if (>= i (count h)) out")
print("    (recur (+ i 2) (str out (chr (+ (* 16 (hexd (nth h i))) (hexd (nth h (+ i 1))))))))))")
print()
print(f'(def H "{h(H)}")')
print(f'(def ED-BLOB "{h(ED_BLOB)}")')
print(f'(def ED-SIG "{h(ED_SIG)}")')
print(f'(def RSA-BLOB "{h(RSA_BLOB)}")')
print(f'(def RSA-SIG256 "{h(RSA_SIG256)}")')
print(f'(def RSA-SIG512 "{h(RSA_SIG512)}")')
print(f'(def RSA-SIG1 "{h(RSA_SIG1)}")')
print(f'(def SMALL-BLOB "{h(SMALL_BLOB)}")')
print(f'(def SMALL-SIG "{h(SMALL_SIG)}")')
print(f'(def EC-BLOB "{h(EC_BLOB)}")')
print(f'(def EC-SIG "{h(EC_SIG)}")')
print(f'(def ED-B64 "{b64(ED_BLOB)}")')
print(f'(def EC-B64 "{b64(EC_BLOB)}")')
print(f'(def RSA-B64 "{b64(RSA_BLOB)}")')
print(f'(def HASH-PLAIN "{HASH_PLAIN}")')
print(f'(def HASH-PORT "{HASH_PORT}")')
print()
print("(defn- verify Str [alg: Str blob: Str sig: Str data: Str] (k/verify-signature alg (unhex blob) (unhex sig) (unhex data)))")
print()
print(";; 交渉した方式で、ホスト鍵が H に付けた署名を確かめる")
print("(deftest signatures-good")
print('  (is (= (verify "ssh-ed25519" ED-BLOB ED-SIG H) ""))')
print('  (is (= (verify "rsa-sha2-256" RSA-BLOB RSA-SIG256 H) ""))')
print('  (is (= (verify "rsa-sha2-512" RSA-BLOB RSA-SIG512 H) ""))')
print('  (is (= (verify "ecdsa-sha2-nistp256" EC-BLOB EC-SIG H) "")))')
print()
print(";; ecdsa-sha2-nistp256 (RFC 5656 3.1): 違うデータ、壊れた署名、曲線の名前の違う鍵")
print("(deftest signatures-ecdsa-bad")
print('  (is (not= (verify "ecdsa-sha2-nistp256" EC-BLOB EC-SIG (str H "00")) ""))')
print('  (is (not= (verify "ecdsa-sha2-nistp256" EC-BLOB (str (subs EC-SIG 0 (- (count EC-SIG) 2)) "00") H) ""))')
print('  (is (not= (verify "ecdsa-sha2-nistp256" ED-BLOB ED-SIG H) ""))')
print('  (is (not= (verify "ssh-ed25519" EC-BLOB EC-SIG H) ""))')
print('  (is (not= (k/verify-signature "ecdsa-sha2-nistp256" (str (subs (unhex EC-BLOB) 0 27) "nistp384" (subs (unhex EC-BLOB) 35 (count (unhex EC-BLOB)))) (unhex EC-SIG) (unhex H)) "")))')
print()
print(";; known_hosts に行のある鍵の種類 (ホスト鍵の方式の並びで先に出す)。ssh-rsa は rsa-sha2-512 と rsa-sha2-256")
print("(deftest known-algorithms")
print('  (let [t (str "[127.0.0.1]:2222 ecdsa-sha2-nistp256 " EC-B64 "\\nother ssh-ed25519 " ED-B64 "\\n[127.0.0.1]:2222 ssh-rsa " RSA-B64 "\\n@revoked [127.0.0.1]:2222 ssh-ed25519 " ED-B64 "\\n")]')
print('    (is (= (k/known-algorithms t "127.0.0.1" 2222) ["ecdsa-sha2-nistp256" "rsa-sha2-512" "rsa-sha2-256"]))')
print('    (is (= (k/known-algorithms t "other" 22) ["ssh-ed25519"]))')
print('    (is (= (k/known-algorithms t "nobody" 22) (let [e: Vec(Str) []] e)))))')
print()
print(";; 鍵の blob の名前は ssh-rsa のまま、署名の blob の名前は交渉した方式でなければならない (RFC 8332 3 節)")
print("(deftest signatures-bad")
print('  (is (not= (verify "rsa-sha2-256" RSA-BLOB RSA-SIG512 H) ""))')
print('  (is (not= (verify "rsa-sha2-512" RSA-BLOB RSA-SIG256 H) ""))')
print('  (is (not= (verify "rsa-sha2-256" RSA-BLOB RSA-SIG1 H) ""))')
print('  (is (not= (verify "ssh-ed25519" RSA-BLOB RSA-SIG256 H) ""))')
print('  (is (not= (verify "rsa-sha2-256" ED-BLOB ED-SIG H) ""))')
print('  (is (not= (verify "ssh-ed25519" ED-BLOB ED-SIG (str H "00")) ""))')
print('  (is (not= (verify "rsa-sha2-256" RSA-BLOB RSA-SIG256 (str H "00")) ""))')
print('  (is (not= (verify "ssh-ed25519" ED-BLOB (str ED-SIG "00") H) ""))')
print('  (is (not= (verify "ssh-ed25519" (str ED-BLOB "00") ED-SIG H) ""))')
print('  (is (not= (verify "ssh-ed25519" ED-BLOB (subs ED-SIG 0 (- (count ED-SIG) 2)) H) ""))')
print('  (is (not= (verify "ssh-dss" ED-BLOB ED-SIG H) ""))')
print(";; 1024 ビットの RSA は通す (OpenSSH の RequiredRSASize の既定と同じ下限)。1023 ビット以下は断る")
print('  (is (= (verify "rsa-sha2-256" SMALL-BLOB SMALL-SIG H) ""))')
print('  (is (k/rsa-bits-ok? (str (chr 128) (subs (unhex H) 0 31) (unhex H) (unhex H) (unhex H))))')
print('  (is (not (k/rsa-bits-ok? (str (chr 127) (subs (unhex H) 0 31) (unhex H) (unhex H) (unhex H))))))')
print()
print(";; known_hosts の照合。ポートが 22 でなければ [host]:port で引く")
print("(deftest known-hosts-plain")
print('  (let [blob (unhex ED-BLOB) rsab (unhex RSA-BLOB)')
print('        t1 (str "# c\\n\\n[127.0.0.1]:2222 ssh-ed25519 " ED-B64 " comment\\n")')
print('        t2 (str "host1,Example.ORG,10.0.0.1 ssh-ed25519 " ED-B64 "\\n")')
print('        t3 (str "*.example.com,!bad.example.com ssh-ed25519 " ED-B64 "\\n")')
print('        t4 (str "h?st ssh-rsa " RSA-B64 "\\n")]')
print('    (is (k/known? t1 "127.0.0.1" 2222 blob))')
print('    (is (not (k/known? t1 "127.0.0.1" 22 blob)))')
print('    (is (not (k/known? t1 "127.0.0.1" 2222 rsab)))')
print('    (is (k/known? t2 "example.org" 22 blob))')
print('    (is (k/known? t2 "10.0.0.1" 22 blob))')
print('    (is (not (k/known? t2 "10.0.0.2" 22 blob)))')
print('    (is (not (k/known? t2 "example.org" 2222 blob)))')
print('    (is (k/known? t3 "a.example.com" 22 blob))')
print('    (is (not (k/known? t3 "bad.example.com" 22 blob)))')
print('    (is (not (k/known? t3 "example.com" 22 blob)))')
print('    (is (k/known? t4 "host" 22 rsab))')
print('    (is (not (k/known? t4 "hoost" 22 rsab)))')
print('    (is (not (k/known? t4 "host" 22 blob)))))')
print()
print(";; ハッシュされた名前 (|1|salt|hash)、@revoked (一致すれば他の行があっても断る)、@cert-authority (飛ばす)、壊れた行")
print("(deftest known-hosts-markers")
print('  (let [blob (unhex ED-BLOB)')
print('        th (str HASH-PLAIN " ssh-ed25519 " ED-B64 "\\n" HASH-PORT " ssh-ed25519 " ED-B64 "\\n")')
print('        tr (str "[127.0.0.1]:2222 ssh-ed25519 " ED-B64 "\\n@revoked * ssh-ed25519 " ED-B64 "\\n")')
print('        tc (str "@cert-authority [127.0.0.1]:2222 ssh-ed25519 " ED-B64 "\\n")')
print('        tb (str "[127.0.0.1]:2222 ssh-ed25519 !!!notbase64\\n[127.0.0.1]:2222\\n@revoked\\n|1|x|y ssh-ed25519 " ED-B64 "\\n")]')
print('    (is (k/known? th "example.org" 22 blob))')
print('    (is (k/known? th "127.0.0.1" 2222 blob))')
print('    (is (not (k/known? th "example.com" 22 blob)))')
print('    (is (not (k/known? tr "127.0.0.1" 2222 blob)))')
print('    (is (not (k/known? tc "127.0.0.1" 2222 blob)))')
print('    (is (not (k/known? tb "127.0.0.1" 2222 blob)))')
print('    (is (k/known? (str tb "[127.0.0.1]:2222 ssh-ed25519 " ED-B64) "127.0.0.1" 2222 blob))))')
