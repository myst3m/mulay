// Generates test/wsdl/golden_test.clay: what mule-wsdl-parser 1.4.11 (the parser that the Web Service Consumer 2.2.2
// plugin ships with mule-soap-engine 2.4.0; WsdlParser.Companion.parse(location, locator, encoding)) reads from the WSDL
// files in test/wsdl/data, as text that mulay.lib.wsdl must reproduce.
// Run (the jars are the plugin's dependencies in the built wsc-ops fixture: tools/mule-oracle/mule-oracle fill wsc-ops):
//   R=target/mule-oracle-build/wsc-ops/target/repository
//   M=~/srv/mule-enterprise-standalone-4.11.3
//   CP=$(find $R -name '*.jar' ! -name '*mule-plugin*' | tr '\n' ':'):$(ls $M/lib/mule/*.jar $M/lib/opt/*.jar | tr '\n' ':')
//   /usr/lib/jvm/java-17-openjdk-amd64/bin/java -cp "$CP" tools/gen-wsdl-golden.java > test/wsdl/golden_test.clay
import java.io.File;
import java.util.*;
import org.mule.wsdl.parser.WsdlParser;
import org.mule.wsdl.parser.model.*;
import org.mule.wsdl.parser.model.operation.*;

public class GenWsdlGolden {
    static final String DIR = "test/wsdl/data";
    static final String[] FILES = {"echo.wsdl", "calc-rpc.wsdl", "imp/service.wsdl", "multi.wsdl", "rpc-op.wsdl",
        "broken.wsdl", "empty.wsdl", "notxml.wsdl", "notwsdl.wsdl", "badimport.wsdl", "noports.wsdl", "badref.wsdl", "nostyle.wsdl", "missing.wsdl"};

    static String q(String s) { return s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n"); }

    static String show(WsdlModel m) {
        StringBuilder b = new StringBuilder();
        b.append("style=").append(m.getStyle()).append("\n");
        List<ServiceModel> ss = new ArrayList<>(m.getServices());
        ss.sort(Comparator.comparing(ServiceModel::getName));   // 並びは HashMap の順で、WSC には出ないので名前の順にする
        for (ServiceModel s : ss) {
            b.append("service ").append(s.getName()).append("\n");
            List<PortModel> ps = new ArrayList<>(s.getPorts());
            ps.sort(Comparator.comparing(PortModel::getName));
            for (PortModel p : ps) {
                String addr;
                try { addr = String.valueOf(p.getAddress()); } catch (Exception e) { addr = "!" + e.getClass().getSimpleName(); }
                SoapBinding sb = p.getBinding();
                b.append(" port ").append(p.getName()).append(" address=").append(addr)
                 .append(" binding=").append(sb == null ? "null" : sb.getVersion() + "/" + sb.getStyle()).append("\n");
                List<OperationModel> os = new ArrayList<>(p.getOperations());
                os.sort(Comparator.comparing(OperationModel::getName));
                for (OperationModel o : os) {
                    String act = o.getSoapAction();
                    b.append("  op ").append(o.getName()).append(" type=").append(o.getType())
                     .append(" action=").append(act == null ? "null" : "[" + act + "]").append("\n");
                }
            }
        }
        return b.toString();
    }

    public static void main(String[] args) throws Exception {
        StringBuilder out = new StringBuilder();
        out.append("(ns wsdl-golden-test (:require [wsdl-golden-helper :as h]))\n");
        out.append(";; GENERATED by tools/gen-wsdl-golden.java on Java " + System.getProperty("java.version") + " (mule-wsdl-parser 1.4.11) -- do not edit.\n");
        out.append(";; 失敗は \"!<例外の単純名>: <文言>\" (文言の中の data の絶対パスは <DIR>、カレントディレクトリは <CWD> に置き換える)。\n");
        out.append(";; service、port、操作は名前の順 (実物の並びは HashMap の順で、WSC の振る舞いには出ない)。\n");
        out.append("(deftest golden-wsdl\n");
        String abs = new File(DIR).getAbsolutePath();
        String cwd = new File("").getAbsolutePath();
        for (String f : FILES) {
            String r;
            try {
                r = show(WsdlParser.Companion.parse(new File(DIR, f).toURI().toURL().toString()));
            } catch (Throwable e) {
                r = "!" + e.getClass().getSimpleName() + ": " + String.valueOf(e.getMessage()).replace(abs, "<DIR>").replace(cwd, "<CWD>");
            }
            out.append("  (is (= (h/show \"" + q(f) + "\") \"" + q(r) + "\"))\n");
        }
        out.append(")\n");
        System.out.print(out);
    }
}
