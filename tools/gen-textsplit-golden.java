// Generates test/textsplit/golden_test.clay: langchain4j 1.1.0 DocumentSplitters.recursive(max, overlap) and the
// sentence detector (OpenNLP 2.5.4, opennlp-en-ud-ewt-sentence) that mulay.lib.textsplit approximates
// (Vectors の transform-chunk-text)。
// Run:
//   R=~/.m2/repository
//   CP=$R/dev/langchain4j/langchain4j/1.1.0/langchain4j-1.1.0.jar:$R/dev/langchain4j/langchain4j-core/1.1.0/langchain4j-core-1.1.0.jar:$R/org/apache/opennlp/opennlp-tools/2.5.4/opennlp-tools-2.5.4.jar:$(ls $R/org/slf4j/slf4j-api/2.0.17/*.jar)
//   /usr/lib/jvm/java-17-openjdk-amd64/bin/java -cp "$CP" tools/gen-textsplit-golden.java > test/textsplit/golden_test.clay
import java.nio.charset.StandardCharsets;
import java.util.*;
import dev.langchain4j.data.document.Document;
import dev.langchain4j.data.document.splitter.DocumentSplitters;
import dev.langchain4j.data.document.splitter.DocumentBySentenceSplitter;
import dev.langchain4j.data.segment.TextSegment;

public class GenTextsplitGolden {
    static String hex(String s) {
        StringBuilder b = new StringBuilder();
        for (byte x : s.getBytes(StandardCharsets.UTF_8)) b.append(String.format("%02x", x & 0xff));
        return b.toString();
    }
    static String show(String s) { return s.replace("\n", "\\n").replace("\t", "\\t"); }

    static final String P = "Mule runs integrations. It is fast.\n\nAgents use tools! Do they work? Yes, they do.\nA new line here.\n\n"
        + "The last paragraph is a little longer than the others, so it has to be split into pieces by words.";
    static final String[] TEXTS = {
        P,
        "Dr. Smith went to Washington. He arrived at 3 p.m. on Jan. 5. It rained.",
        "One two three four five six seven eight nine ten eleven twelve.",
        "Short text.",
        "Orders ship in two days. Refunds take a week after the order is returned. Contact support if anything goes wrong.",
        "Mr. and Mrs. Jones live in the U.S. now. They moved in 2020. Life is good!",
        "What is RAG? It retrieves documents. Then it asks the LLM.",
        "Line one\nLine two\nLine three is longer than the others by a fair amount\n\n\nNew paragraph after blank lines.",
        "  Leading spaces. And trailing.  ",
        "Supercalifragilisticexpialidocious is a very long word indeed.",
        "e.g. this starts with an abbreviation. Then a normal sentence.",
        "The price is $3.50 today. It was 4.75 yesterday.",
        "\"Quoted sentence.\" Another one. (Parenthesized.) Last.",
        "No terminal punctuation here",
        "日本語の文。二つ目の文。",
    };
    // OpenNLP のモデルの文の切り方に mulay の規則が合わない組 (docs/compat/deviations.md)。アサーションにせず注釈で残す。
    // 文: 1 ("p.m. on" で切る、"Jan. 5." の "5." を 1 文にする)。分割: 1 は全部、4 の 5/2、10 の 10/10、12 の 5/2。
    static boolean knownSentence(int t) { return t == 1; }
    static boolean knownRecursive(int t, int max, int ov) {
        return t == 1 || (t == 4 && max == 5) || (t == 10 && max == 10) || (t == 12 && max == 5);
    }
    static final int[][] SIZES = {{20, 0}, {20, 5}, {25, 10}, {40, 0}, {40, 15}, {60, 20}, {100, 30}, {1000, 0}, {10, 10}, {5, 2}};

    public static void main(String[] args) {
        StringBuilder out = new StringBuilder();
        out.append("(ns textsplit-golden-test (:require [textsplit-golden-helper :as h]))\n");
        out.append(";; GENERATED by tools/gen-textsplit-golden.java on Java " + System.getProperty("java.version")
                   + " (langchain4j 1.1.0, OpenNLP 2.5.4) -- do not edit.\n");
        out.append(";; 断片は \\u0001 で区切る。\n");
        DocumentBySentenceSplitter ss = new DocumentBySentenceSplitter(1, 0);
        out.append("(deftest golden-sentences\n");
        for (int ti = 0; ti < TEXTS.length; ti++) {
            String t = TEXTS[ti];
            String r = String.join("\u0001", ss.split(t));
            out.append("  ;; " + show(t) + "\n");
            if (knownSentence(ti)) out.append("  ;; 既知の違い。実物: " + show(r.replace("\u0001", " | ")) + "\n");
            else out.append("  (is (= (h/sentences \"" + hex(t) + "\") \"" + hex(r) + "\"))\n");
        }
        out.append(")\n(deftest golden-recursive\n");
        for (int ti = 0; ti < TEXTS.length; ti++) for (int[] sz : SIZES) {
            String t = TEXTS[ti];
            String r;
            try {
                List<TextSegment> segs = DocumentSplitters.recursive(sz[0], sz[1]).split(Document.from(t));
                List<String> xs = new ArrayList<>();
                for (TextSegment s : segs) xs.add(s.text());
                r = String.join("\u0001", xs);
            } catch (RuntimeException e) {
                r = "!" + e.getMessage();
            }
            out.append("  ;; " + sz[0] + "/" + sz[1] + " " + show(t).substring(0, Math.min(40, show(t).length())) + "\n");
            if (knownRecursive(ti, sz[0], sz[1])) out.append("  ;; 既知の違い。実物: " + show(r.replace("\u0001", " | ")) + "\n");
            else out.append("  (is (= (h/recursive \"" + hex(t) + "\" " + sz[0] + " " + sz[1] + ") \"" + hex(r) + "\"))\n");
        }
        out.append(")\n");
        System.out.print(out);
    }
}
