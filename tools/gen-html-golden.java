import java.nio.charset.StandardCharsets;
import org.apache.commons.text.StringEscapeUtils;

public class GenHtmlGolden {
    static String hex(byte[] bs) {
        StringBuilder b = new StringBuilder();
        for (byte x : bs) b.append(String.format("%02x", x & 0xff));
        return b.toString();
    }
    static String case_(byte[] in) {
        String s = new String(in, StandardCharsets.ISO_8859_1);
        String e = StringEscapeUtils.escapeHtml4(s);
        return "  (is (= (h/esc \"" + hex(in) + "\") \"" + hex(e.getBytes(StandardCharsets.UTF_8)) + "\"))\n";
    }
    public static void main(String[] args) {
        StringBuilder out = new StringBuilder();
        out.append("(ns html-golden-test (:require [html-helper :as h]))\n");
        out.append(";; GENERATED by tools/gen-html-golden.java on Java " + System.getProperty("java.version")
                   + " (commons-text 1.14.0) -- do not edit.\n");
        out.append(";; 入力と期待値は 16 進。入力の各バイトを ISO-8859-1 の文字として escapeHtml4 し、UTF-8 にしたもの。\n");
        for (int base = 0; base < 256; base += 64) {
            out.append("(deftest every-byte-" + base + "\n");
            for (int b = base; b < base + 64; b++) out.append(case_(new byte[]{(byte) b}));
            out.append(")\n");
        }
        String[] strs = {"", "/nope/a&b", "/nope/a:b@c!$&'()*+,=~", "&amp;", "<a href=\"x\">'y'</a>"};
        byte[][] raw = {{(byte) 0x2f, (byte) 0xc3, (byte) 0xa9}, {(byte) 0xe3, (byte) 0x81, (byte) 0x82, (byte) 0x26}};
        out.append("(deftest strings\n");
        for (String s : strs) out.append(case_(s.getBytes(StandardCharsets.ISO_8859_1)));
        for (byte[] r : raw) out.append(case_(r));
        out.append(")\n");
        System.out.print(out);
    }
}
